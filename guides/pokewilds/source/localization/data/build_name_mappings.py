# This directory contains four artwork files and no base_stats/wilds_data data.
# It has no official species ID and cannot be treated as a real Pokémon entry.
UNUSED_ARTWORK_IDS = {"straigar"}


def norm(value):
    return re.sub(r"[^a-z0-9]", "", value.lower())


def read_csv(name):
    with (EVIDENCE / "pokeapi" / (name + ".csv")).open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def read_properties(path):
    data = {}
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if not line or line.lstrip().startswith(("#", "!")):
            continue
        key, value = line.split("=", 1)
        key = key.replace("\\ ", " ")
        assert key not in data, (path, "duplicate key", key)
        data[key] = value
    return data


def translated_table(table, singular, id_column):
    rows = read_csv(singular + "_names")
    translated = {row[id_column]: row["name"] for row in rows if row["local_language_id"] == LANGUAGE_ID}
    identifiers = {norm(row["identifier"]): row["id"] for row in read_csv(table)}
    identifiers.update({norm(row["name"]): row[id_column] for row in rows if row["local_language_id"] == "9"})
    return {key: translated[value] for key, value in identifiers.items() if value in translated}, identifiers


def write_bundle(name, mapping, original):
    missing = set(original) - set(mapping)
    assert not missing, (name, "missing", sorted(missing))
    for key, value in mapping.items():
        assert value and re.search(r"[\u3400-\u9fff]", value), (name, key, value)
        assert "\n" not in value and "\r" not in value
    out = ROOT / "zh_CN"
    out.mkdir(exist_ok=True)
    lines = [
        "# UTF-8; generated by localization/build_name_mappings.py",
        "# Source: Chinese official Pokedex + PokeAPI commit " + UPSTREAM_REVISION,
    ]
    def property_key(key):
        # Spaces terminate a key in java.util.Properties / libGDX. Four legacy
        # Tapu keys contain spaces, so encode them while preserving their keys.
        return key.replace("\\", "\\\\").replace(" ", "\\ ")
    lines += [property_key(key) + "=" + mapping[key] for key in original]
    extras = sorted(set(mapping) - set(original))
    if extras:
        lines += ["", "# Additional runtime species aliases and forms"]
        lines += [property_key(key) + "=" + mapping[key] for key in extras]
    (out / (name + "_zh_CN.properties")).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"base_keys": len(original), "translated_keys": len(mapping), "additional_keys": extras, "missing_keys": []}


def build():
    official = json.loads((EVIDENCE / "official-pokedex-cn.json").read_text())["data"]["pokemons"]
    official_species = {str(int(row["zukan_id"])): row["pokemon_name"] for row in official if int(row["zukan_sub_id"]) == 0}
    pokemon_names, pokemon_ids = translated_table("pokemon_species", "pokemon_species", "pokemon_species_id")
    pokemon_names = {key: official_species.get(pid, value) for key, value in pokemon_names.items() for pid in [pokemon_ids[key]]}
    base_pokemon = read_properties(ROOT / "base" / "pokemondisplayname.properties")
    pokemon = {key: pokemon_names[norm(key)] for key in base_pokemon if norm(key) in pokemon_names}
    pokemon.update({"ghost": "幽灵", "egg": "蛋"})
    # Include every ID that the actual checked-in species resources can load.
    resources = ROOT.parent / "source" / "pokemon" / "pokemon"
    resource_ids = sorted(path.name for path in resources.iterdir() if path.is_dir()) if resources.exists() else []
    for key in resource_ids:
        if key in UNUSED_ARTWORK_IDS:
            continue
        if key in pokemon:
            continue
        if norm(key) in pokemon_names:
            pokemon[key] = pokemon_names[norm(key)]
        elif key in FORM_LABELS:
            species, form = FORM_LABELS[key]
            pokemon[key] = form if key.startswith("rotom_") else pokemon_names[norm(species)] + "（" + form + "）"
        elif key.endswith(("_alolan", "_galarian", "_hisuian")):
            species, region = key.rsplit("_", 1)
            pokemon[key] = pokemon_names[norm(species)] + "（" + {"alolan": "阿罗拉", "galarian": "伽勒尔", "hisuian": "洗翠"}[region] + "的样子）"
        elif key.startswith(("flabebe_", "floette_", "florges_")):
            species, color = key.rsplit("_", 1)
            pokemon[key] = pokemon_names[norm(species)] + "（" + {"red": "红", "yellow": "黄", "orange": "橙", "blue": "蓝", "white": "白"}[color] + "花）"
        elif key.startswith(("burmy_", "wormadam_")):
            species, cloak = key.rsplit("_", 1)
            pokemon[key] = pokemon_names[norm(species)] + "（" + {"plant": "草木", "sand": "砂土", "trash": "垃圾"}[cloak] + "蓑衣）"
        elif key.startswith("unown_"):
            form = key.split("_", 1)[1]
            pokemon[key] = pokemon_names["unown"] + "（" + {"qmark": "？", "!": "！"}.get(form, form.upper()) + "）"
        else:
            raise ValueError("Untranslated resource species ID: " + key)
    base_moves = read_properties(ROOT / "base" / "attack.properties")
    move_names, _ = translated_table("moves", "move", "move_id")
    moves = {key: move_names[norm(MOVE_ALIASES.get(key, key))] for key in base_moves}
    base_items = read_properties(ROOT / "base" / "item.properties")
    item_names, _ = translated_table("items", "item", "item_id")
    items = {key: CUSTOM_ITEMS[key] if key in CUSTOM_ITEMS else item_names[norm(ITEM_ALIASES.get(key, key))] for key in base_items}
    report = {
        "sources": {"pokeapi_commit": UPSTREAM_REVISION, "official_pokedex": "https://pokedex.pokemon.cn/play/pokedex/api/v1", "accessed_at": "2026-10-05 Asia/Shanghai"},
        "pokemondisplayname": write_bundle("pokemondisplayname", pokemon, base_pokemon),
        "attack": write_bundle("attack", moves, base_moves),
        "item": write_bundle("item", items, base_items),
        "species_resource_ids_covered": len(resource_ids) - len(UNUSED_ARTWORK_IDS.intersection(resource_ids)),
        "unused_artwork_ids_excluded": sorted(UNUSED_ARTWORK_IDS.intersection(resource_ids)),
        "custom_item_translations": CUSTOM_ITEMS,
        "move_legacy_aliases": MOVE_ALIASES,
        "item_legacy_aliases": ITEM_ALIASES,
        "official_corrections": {"porygon2": "多边兽2型", "minun": "负电拍拍"},
        "notes": ["Official names do not change the original game's combat mechanics.", "Additional form labels describe actual resource IDs; base English lookup keys remain untouched.", "PokeWilds has no upstream code license; PokeAPI data is BSD-3-Clause."]
    }
    (ROOT / "name-mapping-report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({key: report[key] for key in ["pokemondisplayname", "attack", "item", "species_resource_ids_covered"]}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    build()
